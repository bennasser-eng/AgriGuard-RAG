"""script de test pour l'orchestrateur."""

from src.Orchestrator.Orchestrator import Orchestrator

def test_orchestor():
    orchestrator = Orchestrator()
    try:
        # TEST 2: Complex Query
        query = "Puis-je utiliser le produit NEMO sur blé et sur orge au même dosage ?"
        print(f"\n[TEST 2] Query : '{query}'")
        result = orchestrator.answer(query=query)
        print(f"Complexité : {result.get('query_complexity')}")
        
        if "sub_queries" in result:
            print("\n**Sub Questions:**")
            for i, sq in enumerate(result["sub_queries"], 1):
                print(f"{i}. {sq}")
                
        print("\n**Response generated by ReasoningAgent:**")
        print(result["response"])

    finally:
        orchestrator.close()

if __name__ == "__main__":
    test_orchestor()